    (pdk / "sky130_fd_sc_hd.v").write_text("// models\n")
    monkeypatch.setattr(gs, "macro_model_files", lambda *_a, **_k: ([], []))
    net = tmp_path / "net.v"
    net.write_text(netlist)
    return net, tmp_path / "pdk"


