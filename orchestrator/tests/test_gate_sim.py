def test_toolchain_check_precedes_the_netlist_verdict(monkeypatch, tmp_path):
    """The gate must only render a VERDICT where it could actually have run.
    With no simulator/PDK, even a missing netlist is ``not_run`` -- otherwise a
    PDK-free frontend host would fail every block on a gate it cannot execute
    (and, in the pipeline, spin the retry loop)."""
    monkeypatch.setenv(gs.GATE_SIM_ENV, "1")
    monkeypatch.delenv("CORESMITH_GATE_SIM_STRICT", raising=False)
    monkeypatch.setattr(gs.shutil, "which", lambda _n: None)
    res = gs.check_gate_sim(_BLOCK, str(tmp_path / "gone.v"), "r.v", "tb.py")
    assert res.status == gs.STATUS_NOT_RUN
    assert res.blocking is False

    # ...but a host WITH the toolchain and PDK does judge a missing netlist.
    monkeypatch.setattr(gs.shutil, "which", lambda _n: "/usr/bin/verilator")
    pdkdir = tmp_path / "pdk" / "sky130A" / "libs.ref" / "sky130_fd_sc_hd" / "verilog"
    pdkdir.mkdir(parents=True)
    (pdkdir / "sky130_fd_sc_hd.v").write_text("// models\n")
    net = tmp_path / "empty.v"
    net.write_text("   \n")
    res2 = gs.check_gate_sim(_BLOCK, str(net), "r.v", "tb.py",
                             pdk_root=tmp_path / "pdk",
                             work_root=tmp_path / "work")
    assert res2.status == gs.STATUS_FAIL and res2.blocking


