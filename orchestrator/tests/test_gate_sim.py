def _good_ref(tmp_path):
    lines = ["#0", "0!", "0#", "0%", "b0 &", "0("]
    t = 5
    for i in range(6):
        lines += [f"#{t}", "1!", f"b{i % 2} &"]
        lines += [f"#{t + 5}", "0!"]
        t += 10
    return _write_vcd(tmp_path / "d.vcd", lines)


def _runner_for(vcd):
    def runner(*_a, **_k):
        return {"passed": True, "vcd_path": str(vcd)}
    return runner


