def _write_vcd(path, lines):
    path.write_text(
        "$timescale 1ns $end\n"
        "$scope module blk $end\n"
        "$var wire 1 ! clk $end\n"
        "$var wire 1 # rst_n $end\n"
        "$var wire 1 % en $end\n"
        "$var wire 8 & q [7:0] $end\n"
        "$var wire 1 ( valid $end\n"
        "$upscope $end\n"
        "$enddefinitions $end\n" + "\n".join(lines) + "\n"
    )
    return path


def _ports():
    return gs.parse_netlist_ports(_NETLIST, "blk")


def test_extract_vectors_samples_pre_edge_state(tmp_path):
    """The snapshot must be the state BEFORE the edge, even when the VCD lists
    the outputs the edge produced in the SAME timestamp block as the clock."""
    vcd = _write_vcd(tmp_path / "d.vcd", [
        "#0", "0!", "0#", "0%", "b0 &", "0(",
        "#5", "1!",                      # posedge 1: pre-edge q=0
        "#10", "0!",
        "#15", "1%",                     # en rises between edges
        "#20", "1!", "b1 &", "1(",       # posedge 2: q/valid change WITH the clk
        "#25", "0!",
        "#30", "1!", "b10 &",            # posedge 3
    ])
    vec = gs.extract_vectors(vcd, _ports(), "clk", 1000)
    assert vec.cycles == 3
    assert vec.inputs == ["rst_n", "en"]
    assert vec.outputs == ["q", "valid"]
    # cycle 1 pre-edge: en=0, q=0
    assert vec.rows[0] == (["0", "0"], ["00000000", "0"])
    # cycle 2 pre-edge: en=1 (changed at #15), q STILL 0 -- the #20 change is
    # the RESULT of this edge and belongs to the next sample.
    assert vec.rows[1] == (["0", "1"], ["00000000", "0"])
    # cycle 3 pre-edge: q=1 from the previous edge.
    assert vec.rows[2] == (["0", "1"], ["00000001", "1"])
    assert vec.output_activity == 2


def test_extract_vectors_respects_max_cycles(tmp_path):
    lines = ["#0", "0!", "0#", "0%", "b0 &", "0("]
    t = 5
    for _ in range(20):
        lines += [f"#{t}", "1!", f"#{t + 5}", "0!"]
        t += 10
    vcd = _write_vcd(tmp_path / "d.vcd", lines)
    assert gs.extract_vectors(vcd, _ports(), "clk", 4).cycles == 4


def test_extract_vectors_missing_vcd_is_empty(tmp_path):
    assert gs.extract_vectors(tmp_path / "absent.vcd", _ports(), "clk", 10).cycles == 0


def test_write_vector_file_roundtrip(tmp_path):
    vcd = _write_vcd(tmp_path / "d.vcd", [
        "#0", "0!", "0#", "0%", "b0 &", "0(", "#5", "1!", "#10", "0!", "#15", "1!",
    ])
    vec = gs.extract_vectors(vcd, _ports(), "clk", 100)
    out = tmp_path / "v.txt"
    gs.write_vector_file(vec, out, "blk", "clk")
    text = out.read_text()
    assert "# cycles 2" in text
    assert "# in rst_n:1 en:1" in text
    assert "# out q:8 valid:1" in text
    assert text.strip().splitlines()[-1] == "0 0 | 00000000 0"


