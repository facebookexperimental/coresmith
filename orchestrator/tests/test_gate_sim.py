def test_reference_run_is_isolated_and_seed_pinned(monkeypatch, tmp_path):
    """The reference must build in its OWN dir (never clobbering the block's DV
    build) under a PINNED seed, with the shallow port-only trace."""
    net, pdk = _stub_env(monkeypatch, tmp_path)
    seen = {}

    def runner(block, rtl_path, tb_path, attempt=1, extra_defines=None,
               sim_subdir=None, extra_args=None):
        import os as _os
        seen.update({"subdir": sim_subdir, "args": extra_args,
                     "defines": extra_defines,
                     "seed": _os.environ.get("CORESMITH_DV_SEED_PIN")})
        return {"passed": True, "vcd_path": str(_good_ref(tmp_path))}

    monkeypatch.setattr(
        gs, "build_and_run_gate_sim",
        lambda **_k: {"ok": True, "cycles_compared": 6,
                      "output_bits_compared": 54, "diverged": False},
    )
    monkeypatch.delenv("CORESMITH_DV_SEED_PIN", raising=False)
    gs.check_gate_sim(_BLOCK, str(net), "r.v", "tb.py", sim_runner=runner,
                      pdk_root=pdk, work_root=tmp_path / "work")
    assert seen["subdir"] == "blk__gatesim_ref"
    assert seen["args"] == ["--trace-depth 1"]
    assert seen["defines"] is None
    assert seen["seed"]
    # ...and the pin is restored afterwards
    import os as _os
    assert _os.environ.get("CORESMITH_DV_SEED_PIN") is None


