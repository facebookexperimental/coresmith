def complete_build(db, root, module="tiny", *, entry="build_module", seed=None, thread_id=None) -> str:
    """A completed build recorded directly (no graph): the row with its
    inputs, the evidence rows a passing attempt leaves (DV pass, coverage
    closure, synthesis PPA verdict with timing), and the committed pass with
    the produced-output identity. Its completion names the recorded thread,
    but no checkpoint exists for it: the lineage report never calls it the
    intended workflow."""
    from orchestrator.state_store.store import Scoreboard
    inputs = B.module_inputs(db, root, module, seed_path=seed, target_clock_mhz=50.0)
    bid = B.new_build_id(module)
    thread = thread_id or f"build-{bid}"
    B.record_dispatch(db, build_id=bid, module=module, entry=entry, graph="build", thread_id=thread,
                      inputs=inputs, seed=inputs.get("seed"))
    B.mark_started(db, bid)
    sb = Scoreboard(root)
    assert sb.record_dv(block=module, scope="rtl", source="gate", attempt=1, passed=True, build_id=bid, run_id=db.run_id())
    assert sb.record_coverage(block=module, scope="rtl", pct=90.0, attempt=1, source="gate",
                              uncovered={"applicable": True, "floor": 80.0, "passed": True}, build_id=bid)
    assert sb.record_ppa(block=module, attempt=1, source="gate", probe="synth", cells=10, wns_ns=0.5, ppa_ok=True,
                         build_id=bid, stage="synth", tool="yosys+opensta", pdk="sky130A", clock_mhz=50.0,
                         power_mw=None, power_basis="unavailable")
    problems, _rows = B.verify_build_evidence(root, bid, attempt=1, timing_required=True)
    assert problems == [], problems
    tb = Path(root) / "tb" / "cocotb" / f"test_{module}.py"
    if not tb.exists():
        tb.parent.mkdir(parents=True, exist_ok=True)
        tb.write_text("import cocotb\n")
    spec = next((b for b in db.block_specs() if b["name"] == module), {})
    rtl = Path(root) / (spec.get("rtl_target") or f"rtl/{module}.v")
    produced = B.produced_outputs(root, module, inputs.get("target"), tb_path=str(tb), rtl_path=str(rtl))
    assert not produced["missing"], produced
    db.set_result(module, "dv_best", {"sim_passed": True, "build_id": bid})
    db.publish_build_result(module, {"done": True, "sim_passed": True, "synth_success": True, "attempt": 1},
                            build_id=bid, build_result={"attempt": 1, "produced": produced, "timing_required": True,
                                                        "thread_id": thread, "checkpoint_ns": ""})
    return bid


def run_block_done(state: dict, *, thread_id: str) -> dict:
    """``block_done_node`` executed as a node of a compiled LangGraph on a
    checkpointed thread (the node reads its graph identity from the running
    task; outside a graph it refuses to publish)."""
    import asyncio as _asyncio

    from langgraph.checkpoint.memory import MemorySaver
    from langgraph.graph import END, START, StateGraph

    from orchestrator.langgraph import pipeline_graph as pg
    g = StateGraph(pg.BlockState)
    g.add_node("block_done", pg.block_done_node)
    g.add_edge(START, "block_done")
    g.add_edge("block_done", END)
    app = g.compile(checkpointer=MemorySaver())
    return _asyncio.run(app.ainvoke(state, {"configurable": {"thread_id": thread_id}}))


def events(root: Path) -> list[dict]:
    p = Path(root) / ".coresmith" / "pipeline_events.jsonl"
    if not p.exists():
        return []
    return [json.loads(ln) for ln in p.read_text().splitlines() if ln.strip()]


def snapshot_tree(root: Path, rel: str) -> dict[str, str]:
    base = Path(root) / rel
    return {str(p.relative_to(root)): B.file_sha256(p) for p in sorted(base.rglob("*")) if p.is_file()} if base.exists() else {}


