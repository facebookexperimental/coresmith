EDGE = {"edge_id": "tiny__m_out__to__sink__s_in", "producer_block": "tiny", "producer_port": "m_out",
        "consumer_block": "sink", "consumer_port": "s_in", "handshake_protocol": "axi_stream",
        "data_width_bits": 8}

_PRODUCER_RTL = ("module {name}(input clk, input rst_n, output reg [7:0] m_out);\n"
                 "  always @(posedge clk) if (!rst_n) m_out <= 8'd0; else m_out <= m_out + 8'd1;\nendmodule\n")
_CONSUMER_RTL = ("module {name}(input clk, input rst_n, input [7:0] s_in, output reg [7:0] last);\n"
                 "  always @(posedge clk) if (!rst_n) last <= 8'd0; else last <= s_in;\nendmodule\n")


class _Rtl(dict):
    """Synthesizable RTL per module: the first module of a pair produces the
    stream, the second consumes it; any other name gets the producer shape."""

    def __missing__(self, name):
        return _PRODUCER_RTL.format(name=name)


RTL = _Rtl({"tiny": _PRODUCER_RTL.format(name="tiny"), "sink": _CONSUMER_RTL.format(name="sink")})

